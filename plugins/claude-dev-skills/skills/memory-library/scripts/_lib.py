"""Shared helpers for build.py and catalog.py (stdlib only).

Writes go through write_text(), which refuses any path outside <memory>/library/,
so no script can create, modify or delete a fact file at the memory root.
"""
import collections
import datetime
import json
import os
import re
import sys
import zoneinfo

BULK_THRESHOLD = 20  # file-dated entries on one day at/above this are a bulk copy
DATE_RE = re.compile(r'(20\d\d)[-_](\d\d)[-_](\d\d)')
REF_RE = re.compile(r'#(\d{3,5})\b')  # a cited issue or PR number
# date quality -> call-number marker (documented once in references/classification.md)
MARKS = {'exact': '', 'near-exact': '≈', 'not-before': '≥', 'range': '≥', 'not-after': '≤', 'approximate': '~', 'unknown': ''}
LINK_RE = re.compile(r'\]\(([^)]+)\)')
EXTERNAL_RE = re.compile(r'^[A-Za-z][A-Za-z0-9+.-]*://')  # a URL scheme: the entry points outside the memory dir
AUTHORS_FILE = 'authors.json'
UNRECORDED = 'unrecorded'
GENERATED = '<!-- generated by memory-library; edit the source, not this file -->'
EXAMPLE = 'skills/memory-library/references/classes.example.json'


def die(msg):
    sys.stderr.write(msg + '\n')
    sys.exit(2)


def load_classes(mem):
    path = os.path.join(mem, 'library', 'classes.json')
    if not os.path.isfile(path):
        die(f'missing {path}; copy the plugin example ({EXAMPLE}) there and edit it')
    with open(path, encoding='utf-8') as fh:
        cfg = json.load(fh)
    cfg.setdefault('rooms', {})
    cfg.setdefault('shelves', {})
    return cfg


def find_shelf(cfg, ref):
    """Resolve a shelf by code (CI) or directory name (ci-merge)."""
    for code, sh in cfg['shelves'].items():
        if ref in (code, sh['name']):
            return code, sh
    die(f'unknown shelf {ref!r}; known: {", ".join(cfg["shelves"])}')


def room_dir(cfg, code):
    return cfg['rooms'][code]['dir']


def slug(text):
    return re.sub(r'[^a-z0-9_-]+', '-', text.lower()).strip('-') or 'unknown'


def frontmatter(path):
    """Return {key: value} for every `key: value` line in the leading --- block."""
    try:
        with open(path, encoding='utf-8') as fh:
            head = fh.read(4096)
    except OSError:
        return {}
    return parse_frontmatter(head)


def parse_frontmatter(text):
    m = re.match(r'---\s*\n(.*?)\n---', text, re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        kv = re.match(r'\s*([A-Za-z_][\w-]*):\s*(.*?)\s*$', line)
        if kv and kv.group(2):
            out[kv.group(1)] = kv.group(2).strip('"\'')
    return out


def call_number(room, shelf, author, chapter, date, approx=False, mark=None):
    """Facet order is fixed: room -> shelf -> author -> chapter -> date.

    mark is the quality marker (MARKS); approx=True is the legacy spelling of mark '~'."""
    if mark is None:
        mark = '~' if approx else ''
    mark = mark if date != 'unknown' else ''
    return f'{room}.{shelf}/{author}/{chapter}/{mark}{date}'


def sort_key(room, shelf, author, chapter, date):
    return (room, shelf, author, chapter, date)


def write_text(mem, path, text):
    lib = os.path.realpath(os.path.join(mem, 'library')) + os.sep
    real = os.path.realpath(path)
    if not real.startswith(lib):
        raise RuntimeError(f'refusing to write outside library/: {path}')
    os.makedirs(os.path.dirname(real), exist_ok=True)
    if os.path.isfile(real):  # unchanged content keeps its mtime (a full build rewrites only what changed)
        with open(real, encoding='utf-8') as fh:
            if fh.read() == text:
                return
    with open(real, 'w', encoding='utf-8') as fh:
        fh.write(text)


def prune_generated(mem, directory, keep):
    """Delete stale *.md files that carry the generated marker and are not in keep."""
    if not os.path.isdir(directory):
        return
    lib = os.path.realpath(os.path.join(mem, 'library')) + os.sep
    for name in sorted(os.listdir(directory)):
        p = os.path.join(directory, name)
        if not name.endswith('.md') or p in keep or not os.path.realpath(p).startswith(lib):
            continue
        with open(p, encoding='utf-8') as fh:
            if GENERATED in fh.read(400):
                os.remove(p)


def relink(line, mem, frm):
    """Point a topic-style entry's link at the fact file, relative to frm."""
    rel = os.path.relpath(mem, frm)
    return LINK_RE.sub(lambda m: m.group(0) if EXTERNAL_RE.match(m.group(1))
                       else f']({rel}/{os.path.basename(m.group(1))})', line)


def fact_name(line):
    """The fact file an entry links to; None for a line without a link or one linking to a URL (external)."""
    m = LINK_RE.search(line)
    if not m or EXTERNAL_RE.match(m.group(1)):
        return None
    return os.path.basename(m.group(1))


def load_authors(mem):
    """{fact: {author, source}} from library/authors.json; {} when absent or unreadable."""
    try:
        with open(os.path.join(mem, 'library', AUTHORS_FILE), encoding='utf-8') as fh:
            table = json.load(fh)
    except (OSError, ValueError):
        return {}
    return table if isinstance(table, dict) else {}


def recorded_author(table, fact):
    """The author a fact's authors.json entry records (frontmatter or ledger), else None (unrecorded)."""
    entry = table.get(fact) if fact else None
    if isinstance(entry, dict) and entry.get('source') in ('frontmatter', 'ledger') and entry.get('author'):
        return entry['author']
    return None


def source_lines(mem, cfg):
    """{fact file: [entry lines]} from every shelf's flat source topic list."""
    out = collections.defaultdict(list)
    for sh in cfg['shelves'].values():
        src = os.path.join(mem, sh['source'])
        if not os.path.isfile(src):
            continue
        with open(src, encoding='utf-8') as fh:
            for ln in fh:
                if ln.startswith('- ['):
                    out[fact_name(ln)].append(ln.rstrip('\n'))
    return out


def found(date, source, quality, **extra):
    return {'date': date, 'source': source, 'quality': quality, **extra}


def exact_date(fm, lines):
    """created: in the frontmatter, else a date written in an entry; None when neither."""
    for texts, src in (([fm.get('created', '')], 'created'), (lines, 'text')):
        for text in texts:
            d = DATE_RE.search(text)
            if d:
                return found('-'.join(d.groups()), src, 'exact')
    return None


def zone(cfg):
    """tzinfo for day boundaries: classes.json `timezone` (IANA name), else the machine's local zone (None)."""
    name = cfg.get('timezone')
    if not name:
        return None
    try:
        return zoneinfo.ZoneInfo(name)
    except (zoneinfo.ZoneInfoNotFoundError, ValueError):
        die(f'unknown timezone {name!r} in classes.json (use an IANA name such as Europe/Riga)')


def day_of(when, tz):
    """ISO day of an aware datetime in tz; tz None means the machine's local zone."""
    return when.astimezone(tz).date().isoformat()


def file_date(mem, fact, tz=None):
    try:
        st = os.stat(os.path.join(mem, fact))
    except (OSError, TypeError):
        return None
    stamp = getattr(st, 'st_birthtime', st.st_mtime)
    return day_of(datetime.datetime.fromtimestamp(stamp, datetime.timezone.utc), tz)


def date_note(info):
    """Text shown for a bounded date (not-before, range or not-after); empty for every other quality."""
    if info['quality'] == 'not-after':
        return f'≤{info["date"]} (cites #{info["ref"]} from {info["cited_later"]}: added in a later edit)'
    if info['quality'] not in ('not-before', 'range'):
        return ''
    after = f' ≤{info["not_after"]}' if info.get('not_after') else ''
    ref = f' (#{info["ref"]})' if info.get('ref') else ''
    return f'≥{info["date"]}{after}{ref}'
