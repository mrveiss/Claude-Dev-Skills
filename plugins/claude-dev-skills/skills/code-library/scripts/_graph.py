def glob_re(pat):
    out, i = '', 0
    while i < len(pat):
        if pat.startswith('**/', i):
            out += '(?:.*/)?'
            i += 3
        elif pat.startswith('**', i):
            out += '.*'
            i += 2
        elif pat[i] == '*':
            out += '[^/]*'
            i += 1
        elif pat[i] == '?':
            out += '[^/]'
            i += 1
        else:
            out += re.escape(pat[i])
            i += 1
    return re.compile('^' + out + '$')


class Globs:
    def __init__(self, pats):
        self.res = [glob_re(p) for p in pats]

    def match(self, rel):
        return any(r.match(rel) for r in self.res)


def load_config(path):
    """code-classes.json, or {} (auto: room = top directory, shelf = second directory)."""
    if not path:
        return {}
    if not os.path.isfile(path):
        _lib.die(f'missing config {path}; copy references/code-classes.example.json and edit it')
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


class Classifier:
    def __init__(self, cfg):
        self.cfg = cfg
        self.rooms = {c: {**r, 'g': Globs(r.get('globs', []))} for c, r in cfg.get('rooms', {}).items()}
        self.shelves = {c: {**s, 'g': Globs(s.get('globs', []))} for c, s in cfg.get('shelves', {}).items()}
        self.exclude = Globs(cfg.get('exclude', []))
        self.layer_globs = {k: Globs(v) for k, v in {**DEFAULT_LAYER_GLOBS, **cfg.get('layers', {})}.items() if not k.startswith('_')}
        self.ignore = set(cfg.get('fork_ignore_names', DEFAULT_IGNORE_NAMES))
        self.ignore_files = set(cfg.get('fork_ignore_files', DEFAULT_IGNORE_FILES))
        self.fork_skip = Globs(cfg.get('fork_skip_paths', DEFAULT_FORK_SKIP))
        sch = cfg.get('schedulers', {})
        self.sched_dec = sch.get('decorators', _scan.DEFAULT_SCHED_DECORATOR)
        self.sched_name = sch.get('names', _scan.DEFAULT_SCHED_NAME)

    def excluded(self, rel):
        return self.exclude.match(rel)

    def place(self, rel):
        """(room code, room dir, shelf code, shelf dir) for a file."""
        parts = rel.split('/')
        if not self.rooms:
            room = parts[0] if len(parts) > 1 else '_root'
            shelf = parts[1] if len(parts) > 2 else '_top'
            return _lib.slug(room).upper()[:6], _lib.slug(room), _lib.slug(shelf).upper()[:6], _lib.slug(shelf)
        for rc, r in self.rooms.items():
            if r['g'].match(rel):
                for sc, s in self.shelves.items():
                    if s.get('room') == rc and s['g'].match(rel):
                        return rc, r['dir'], sc, s['name']
                return rc, r['dir'], 'OTH', 'other'
        return UNCLASSIFIED[0], UNCLASSIFIED[1], 'OTH', 'other'

    def layer(self, rel):
        for name in ('agent', 'primitive'):
            if name in self.layer_globs and self.layer_globs[name].match(rel):
                return name
        for name in LAYERS:
            if name in self.layer_globs and name not in ('agent', 'primitive') and self.layer_globs[name].match(rel):
                return name
        return 'orchestrator'


def dotted(rel):
    parts = rel[:-3].split('/') if rel.endswith('.py') else rel.split('/')
    if parts and parts[-1] == '__init__':
        parts = parts[:-1]
    return parts


class Resolver:
    """Maps import strings to repo files by dotted-suffix (Python) or relative path (TS/JS/Vue). Text only."""

    def __init__(self, files):
        self.files = set(files)
        self._memo = {}
        self.alias = {}  # '@/x' targets: path after the first /src/ without extension; a dir resolves to its index file
        for rel in sorted(files):
            if '/src/' in rel and rel.endswith(_scan.FE_EXT):
                stem = posixpath.splitext(rel.split('/src/', 1)[1])[0]
                self.alias.setdefault(stem, []).append(rel)
                if posixpath.basename(stem) == 'index':
                    self.alias.setdefault(posixpath.dirname(stem), []).append(rel)
        self.suffix = {}
        for rel in files:
            if rel.endswith('.py'):
                parts = dotted(rel)
                for i in range(len(parts)):
                    self.suffix.setdefault('.'.join(parts[i:]), []).append(rel)

    def python(self, rel, imp):
        key = (rel, imp['module'], imp['name'], imp['level'])
        if key not in self._memo:
            self._memo[key] = self._python(rel, imp)
        return self._memo[key]

    def _python(self, rel, imp):
        mod, level = imp['module'], imp['level']
        if level:
            base = dotted(rel)[:-1] if not rel.endswith('__init__.py') else dotted(rel)
            base = base[:len(base) - (level - 1)] if level > 1 else base
            mod = '.'.join(base + ([mod] if mod else []))
        hits = self.suffix.get(mod, [])
        if imp['name'] and imp['name'] != '*':
            sub = self.suffix.get(f'{mod}.{imp["name"]}' if mod else imp['name'], [])
            if sub and len(sub) <= 3:
                return sorted(sub)
        return sorted(hits) if len(hits) <= 3 else []

    def frontend(self, rel, imp):
        spec = imp['module']
        if spec.startswith('@/'):
            return self.alias.get(spec[2:], [])[:1]
        if not spec.startswith('.'):
            return []
        base = posixpath.normpath(posixpath.join(posixpath.dirname(rel), spec))
        for suf in ('', '.ts', '.tsx', '.js', '.vue', '.mjs', '/index.ts', '/index.js'):
            if base + suf in self.files:
                return [base + suf]
        return []

    def targets(self, rel, rec):
        out = set()
        for imp in rec['imports']:
            out.update(self.python(rel, imp) if rec['lang'] == 'py' else self.frontend(rel, imp))
        out.discard(rel)
        return sorted(out)


def slug_module(rel):
    return _lib.slug(re.sub(r'\.[A-Za-z]+$', '', rel).replace('/', '--'))


def check_out_outside(repo, out):
    r, o = os.path.realpath(repo) + os.sep, os.path.realpath(out) + os.sep
    if o.startswith(r) or o == r:
        _lib.die(f'refusing to write inside the target repo: {out} is under {repo}')


def build_model(repo, cls):
    """Parse every source file once: {'files': {rel: rec}, 'imports': {rel: [rel]}, 'importers': {rel: [rel]}}."""
    rels = [r for r in _scan.walk(repo) if not cls.excluded(r)]
    files = {}
    jobs = [(repo, rel, cls.sched_dec, cls.sched_name) for rel in rels]
    if len(jobs) > 200:  # parsing is pure per file: fan out, order is kept (map), so output stays deterministic
        with multiprocessing.Pool() as pool:
            recs = pool.starmap(_scan.parse_file, jobs, chunksize=64)
    else:
        recs = [_scan.parse_file(*j) for j in jobs]
    for rel, rec in zip(rels, recs):
        rec['test'] = _scan.is_test_path(rel)
        files[rel] = rec
    res = Resolver(rels)
    imports = {rel: res.targets(rel, rec) for rel, rec in files.items()}
    importers = {}
    for rel, tg in imports.items():
        for t in tg:
            importers.setdefault(t, []).append(rel)
    return {'files': files, 'imports': imports, 'importers': {k: sorted(v) for k, v in importers.items()}, 'resolver': res}


def git_head(repo, ref='HEAD'):
    """(sha, commit date) of ref via `git`, which reads objects and runs no repo code; ('unknown', 'unknown') without git."""
    import subprocess
    try:
        out = subprocess.run(['git', '-C', repo, 'log', '-1', '--format=%H %cs', ref], capture_output=True, text=True, check=True).stdout.split()
        return out[0], out[1]
    except (OSError, subprocess.CalledProcessError, IndexError):
        return 'unknown', 'unknown'
